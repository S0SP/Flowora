export function getLanguagePreset(id: string): LanguagePreset | undefined {
  return LANGUAGE_PRESETS.find(p => p.id === id);
}

export function getRecommendedVoicesForLanguage(langId: string): typeof SARVAM_VOICES[number][] {
  const preset = getLanguagePreset(langId);
  if (!preset) return [];
  return SARVAM_VOICES.filter(v => preset.recommendedVoices.includes(v.id));
}
